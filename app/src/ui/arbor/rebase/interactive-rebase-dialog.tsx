import classNames from 'classnames'
import {
  abortInteractiveRebase,
  continueInteractiveRebase,
  getRebasePlan,
  IRebaseTodoEntry,
  runInteractiveRebase,
  RebaseTodoAction,
  validateRebasePlan,
} from '../../../lib/arbor/git/interactive-rebase'
import { getCommits } from '../../../lib/git/log'
import { Commit, shortenSHA } from '../../../models/commit'
import { Repository } from '../../../models/repository'
import { Dispatcher } from '../../dispatcher'
import {
  Dialog,
  DialogContent,
  DialogError,
  DialogFooter,
  OkCancelButtonGroup,
} from '../../dialog'
import { Button } from '../../lib/button'
import { TextArea } from '../../lib/text-area'
import { Octicon } from '../../octicons'
import * as octicons from '../../octicons/octicons.generated'
import {
  getFirstEditSha,
  getRebaseEntryGrouping,
  IRebaseEntryGrouping,
  isRebasePlanUnchanged,
  isSquashOrFixup,
  moveRebaseEntry,
  moveRebaseEntryTo,
  RebaseMoveDirection,
} from './rebase-plan-utils'

/** The number of commits offered when the user picks a starting point. */
const StartCommitCount = 50

/** A selectable action of the rebase plan editor. */
interface IRebaseActionOption {
  readonly value: RebaseTodoAction
  readonly label: string
  /** A short explanation, exposed next to the action and to screen readers. */
  readonly description: string
}

const RebaseActionOptions: ReadonlyArray<IRebaseActionOption> = [
  {
    value: 'pick',
    label: 'Pick',
    description: 'Keep the commit as is',
  },
  {
    value: 'reword',
    label: 'Reword',
    description: 'Keep the changes but edit the commit message',
  },
  {
    value: 'edit',
    label: 'Edit',
    description: 'Stop the rebase to amend the commit',
  },
  {
    value: 'squash',
    label: 'Squash',
    description: 'Fold into the commit above and edit the message',
  },
  {
    value: 'fixup',
    label: 'Fixup',
    description: 'Fold into the commit above and keep its message',
  },
  {
    value: 'drop',
    label: 'Drop',
    description: 'Remove the commit from the history',
  },
]

function getActionOption(action: RebaseTodoAction) {
  const option = RebaseActionOptions.find(o => o.value === action)

  return option === undefined ? RebaseActionOptions[0] : option
}

/** The step of the editor the dialog is currently showing. */
type RebaseStep = 'start' | 'plan' | 'paused'

/** Why the rebase is paused, if it is. */
type RebasePausedOutcome = 'conflicts' | 'stopped-for-edit' | 'error'

interface IInteractiveRebaseDialogState {
  /** The step of the editor currently shown. */
  readonly step: RebaseStep

  /** Whether the commits of the current step are being read from Git. */
  readonly loading: boolean

  /** The most recent commits of the branch, newest first. */
  readonly commits: ReadonlyArray<Commit>

  /** The commit before the first one to rewrite, null for the root commit. */
  readonly baseRef: string | null

  /** The plan being edited, oldest commit first. */
  readonly plan: ReadonlyArray<IRebaseTodoEntry>

  /** The plan as generated by Git, used by the Reset button. */
  readonly originalPlan: ReadonlyArray<IRebaseTodoEntry>

  /** Whether a Git operation is running. */
  readonly busy: boolean

  /** The error to show at the top of the dialog, if any. */
  readonly error: string | null

  /** Why the rebase is paused, if it is. */
  readonly pausedOutcome: RebasePausedOutcome | null

  /** The SHA of the commit the rebase stopped on, if known. */
  readonly pausedSha: string | null

  /** The index of the entry being dragged, if any. */
  readonly draggingIndex: number | null

  /** The index of the entry the dragged entry would be dropped on, if any. */
  readonly dragOverIndex: number | null
}

export interface IInteractiveRebaseDialogProps {
  readonly repository: Repository
  readonly dispatcher: Dispatcher
  /** SHA of the oldest commit to rewrite; undefined lets the user pick it. */
  readonly fromCommitSha?: string
  readonly onDismissed: () => void
}

/** The commit before `sha`, or null when `sha` is the root commit. */
async function getBaseRefForSha(repository: Repository, sha: string) {
  const commits = await getCommits(repository, sha, 1)
  const commit = commits[0]

  if (commit === undefined) {
    throw new Error(`Could not find the commit ${shortenSHA(sha)}.`)
  }

  return getBaseRefForCommit(commit)
}

/** The commit before `commit`, or null when it is the root commit. */
function getBaseRefForCommit(commit: Commit) {
  return commit.parentSHAs.length === 0 ? null : `${commit.sha}^`
}

function describeError(error: unknown) {
  return error instanceof Error ? error.message : String(error)
}

/**
 * Arbor: the interactive rebase editor.
 *
 * The user either picks the oldest commit to rewrite or lands directly on the
 * plan when the graph provided one. Each line of the plan can be reordered
 * (drag and drop, buttons or Alt+Up/Down) and given an action, then the plan
 * is handed over to `runInteractiveRebase`.
 */
export class InteractiveRebaseDialog extends React.Component<
  IInteractiveRebaseDialogProps,
  IInteractiveRebaseDialogState
> {
  private isMounted = false

  /** The rendered rows of the plan, keyed by SHA, used to restore focus. */
  private readonly entryElements = new Map<string, HTMLLIElement>()

  public constructor(props: IInteractiveRebaseDialogProps) {
    super(props)

    this.state = {
      step: props.fromCommitSha === undefined ? 'start' : 'plan',
      loading: true,
      commits: [],
      baseRef: null,
      plan: [],
      originalPlan: [],
      busy: false,
      error: null,
      pausedOutcome: null,
      pausedSha: null,
      draggingIndex: null,
      dragOverIndex: null,
    }
  }

  public componentDidMount() {
    this.isMounted = true
    this.loadInitialPlan()
  }

  public componentWillUnmount() {
    this.isMounted = false
    this.entryElements.clear()
  }

  private onFormSubmit = () => {
    this.startRebase()
  }

  private onOkButtonClick = (event: React.MouseEvent<HTMLButtonElement>) => {
    event.preventDefault()
    this.startRebase()
  }

  private onCancelButtonClick = (
    event: React.MouseEvent<HTMLButtonElement>
  ) => {
    event.preventDefault()
    this.props.onDismissed()
  }

  private onResetClick = () => {
    this.setState({ plan: this.state.originalPlan, error: null })
  }

  private onChangeStartClick = () => {
    this.setState({
      step: 'start',
      loading: false,
      plan: [],
      originalPlan: [],
      baseRef: null,
      error: null,
      pausedOutcome: null,
      pausedSha: null,
    })
  }

  private onStartEntryClick = (event: React.MouseEvent<HTMLLIElement>) => {
    this.chooseStartCommit(event.currentTarget.dataset.sha)
  }

  private onStartEntryKeyDown = (event: React.KeyboardEvent<HTMLLIElement>) => {
    if (event.key !== 'Enter' && event.key !== ' ') {
      return
    }

    event.preventDefault()
    this.chooseStartCommit(event.currentTarget.dataset.sha)
  }

  private onActionChanged = (event: React.FormEvent<HTMLSelectElement>) => {
    const action = event.currentTarget.value as RebaseTodoAction
    const index = this.findEntryIndex(
      this.getEntryShaFromElement(event.currentTarget)
    )

    if (index < 0) {
      return
    }

    this.updateEntry(index, entry => ({
      ...entry,
      action,
      message:
        action === 'reword'
          ? entry.summary
          : isSquashOrFixup(action)
          ? entry.message
          : undefined,
    }))
  }

  private onMessageChanged = (event: React.FormEvent<HTMLTextAreaElement>) => {
    const value = event.currentTarget.value
    const index = this.findEntryIndex(
      this.getEntryShaFromElement(event.currentTarget)
    )

    this.updateEntry(index, entry => ({ ...entry, message: value }))
  }

  private onMoveUpClick = (event: React.MouseEvent<HTMLButtonElement>) => {
    this.moveEntryBySha(this.getEntryShaFromElement(event.currentTarget), 'up')
  }

  private onMoveDownClick = (event: React.MouseEvent<HTMLButtonElement>) => {
    this.moveEntryBySha(
      this.getEntryShaFromElement(event.currentTarget),
      'down'
    )
  }

  private onEntryKeyDown = (event: React.KeyboardEvent<HTMLLIElement>) => {
    if (
      !event.altKey ||
      event.target instanceof HTMLTextAreaElement ||
      (event.key !== 'ArrowUp' && event.key !== 'ArrowDown')
    ) {
      return
    }

    const index = this.findEntryIndex(event.currentTarget.dataset.sha)

    if (index < 0) {
      return
    }

    event.preventDefault()
    this.moveEntry(index, event.key === 'ArrowUp' ? 'up' : 'down')
  }

  private onEntryRef = (element: HTMLLIElement | null) => {
    if (element === null) {
      return
    }

    const sha = element.dataset.sha

    if (sha !== undefined) {
      this.entryElements.set(sha, element)
    }
  }

  private onDragStart = (event: React.DragEvent<HTMLLIElement>) => {
    const sha = event.currentTarget.dataset.sha
    const index = this.findEntryIndex(sha)

    if (index < 0) {
      return
    }

    event.dataTransfer.effectAllowed = 'move'
    event.dataTransfer.setData('text/plain', sha ?? '')
    this.setState({ draggingIndex: index })
  }

  private onDragOver = (event: React.DragEvent<HTMLLIElement>) => {
    const index = this.findEntryIndex(event.currentTarget.dataset.sha)

    if (this.state.draggingIndex === null || index < 0) {
      return
    }

    event.preventDefault()
    event.dataTransfer.dropEffect = 'move'

    if (this.state.dragOverIndex !== index) {
      this.setState({ dragOverIndex: index })
    }
  }

  private onDrop = (event: React.DragEvent<HTMLLIElement>) => {
    event.preventDefault()

    const from = this.state.draggingIndex
    const to = this.findEntryIndex(event.currentTarget.dataset.sha)

    this.setState({ draggingIndex: null, dragOverIndex: null })

    if (from === null || to < 0) {
      return
    }

    this.moveEntryTo(from, to)
  }

  private onDragEnd = () => {
    this.setState({ draggingIndex: null, dragOverIndex: null })
  }

  private onContinueClick = () => {
    this.continueRebase()
  }

  private onAbortClick = () => {
    this.abortRebase()
  }

  /** The error reported by `validateRebasePlan` for the current plan. */
  private getValidationError() {
    const plan = this.state.plan

    return plan.length === 0 ? null : validateRebasePlan(plan)
  }

  /** Whether the current plan can be handed over to Git. */
  private canStartRebase() {
    const { step, plan, originalPlan, busy } = this.state

    if (step !== 'plan' || busy || plan.length === 0) {
      return false
    }

    return (
      validateRebasePlan(plan) === null &&
      !isRebasePlanUnchanged(originalPlan, plan)
    )
  }

  /** The tooltip explaining why the Start rebase button is disabled. */
  private getStartButtonTitle() {
    const { step, busy } = this.state

    if (busy) {
      return undefined
    }

    if (step === 'start') {
      return 'Choose the oldest commit to rewrite first'
    }

    const validationError = this.getValidationError()

    if (validationError !== null) {
      return validationError
    }

    return isRebasePlanUnchanged(this.state.originalPlan, this.state.plan)
      ? 'Change at least one action to start the rebase'
      : undefined
  }

  private getEntryShaFromElement(element: Element) {
    const row = element.closest('.arbor-rebase-entry')

    return row instanceof HTMLElement ? row.dataset.sha : undefined
  }

  private findEntryIndex(sha: string | undefined) {
    return sha === undefined
      ? -1
      : this.state.plan.findIndex(entry => entry.sha === sha)
  }

  private updateEntry(
    index: number,
    update: (entry: IRebaseTodoEntry) => IRebaseTodoEntry
  ) {
    const plan = this.state.plan

    if (index < 0 || index >= plan.length) {
      return
    }

    const updated = plan.slice()
    updated[index] = update(plan[index])

    this.setState({ plan: updated })
  }

  private moveEntryBySha(
    sha: string | undefined,
    direction: RebaseMoveDirection
  ) {
    const index = this.findEntryIndex(sha)

    if (index >= 0) {
      this.moveEntry(index, direction)
    }
  }

  private moveEntry(index: number, direction: RebaseMoveDirection) {
    const plan = moveRebaseEntry(this.state.plan, index, direction)

    if (plan === this.state.plan) {
      return
    }

    this.moveToPlan(plan, direction === 'up' ? index - 1 : index + 1)
  }

  private moveEntryTo(from: number, to: number) {
    const plan = moveRebaseEntryTo(this.state.plan, from, to)

    if (plan === this.state.plan) {
      return
    }

    this.moveToPlan(plan, to)
  }

  /** Apply a reordered plan and keep the keyboard focus on the moved entry. */
  private moveToPlan(plan: ReadonlyArray<IRebaseTodoEntry>, index: number) {
    const entry = plan[index]

    this.setState({ plan }, () => {
      if (entry !== undefined) {
        this.entryElements.get(entry.sha)?.focus()
      }
    })
  }

  private async loadInitialPlan() {
    const { repository, fromCommitSha } = this.props

    if (fromCommitSha === undefined) {
      await this.loadCommits()
      return
    }

    this.setState({ loading: true, error: null })

    try {
      const baseRef = await getBaseRefForSha(repository, fromCommitSha)
      const plan = await getRebasePlan(repository, baseRef)

      if (!this.isMounted) {
        return
      }

      this.setState({ loading: false, baseRef, plan, originalPlan: plan })
    } catch (e) {
      if (this.isMounted) {
        this.setState({ loading: false, error: describeError(e) })
      }
    }
  }

  private async loadCommits() {
    this.setState({ loading: true, error: null })

    try {
      const commits = await getCommits(
        this.props.repository,
        'HEAD',
        StartCommitCount
      )

      if (this.isMounted) {
        this.setState({ loading: false, commits })
      }
    } catch (e) {
      if (this.isMounted) {
        this.setState({ loading: false, error: describeError(e) })
      }
    }
  }

  private async chooseStartCommit(sha: string | undefined) {
    const commit = this.state.commits.find(c => c.sha === sha)

    if (commit === undefined || this.state.loading) {
      return
    }

    const baseRef = getBaseRefForCommit(commit)

    this.setState({ loading: true, error: null })

    try {
      const plan = await getRebasePlan(this.props.repository, baseRef)

      if (!this.isMounted) {
        return
      }

      this.setState({
        loading: false,
        step: 'plan',
        baseRef,
        plan,
        originalPlan: plan,
        error: null,
      })
    } catch (e) {
      if (this.isMounted) {
        this.setState({ loading: false, error: describeError(e) })
      }
    }
  }

  private async startRebase() {
    const { repository, dispatcher } = this.props
    const { plan, baseRef, busy, step } = this.state

    if (busy || step !== 'plan' || !this.canStartRebase()) {
      return
    }

    this.setState({ busy: true, error: null })

    try {
      const outcome = await runInteractiveRebase(repository, baseRef, plan)

      await dispatcher.refreshRepository(repository)

      if (!this.isMounted) {
        return
      }

      switch (outcome) {
        case 'completed':
          this.props.onDismissed()
          return
        case 'conflicts':
        case 'stopped-for-edit':
          // Desktop detects the paused rebase on refresh and shows its own
          // "Continue rebase" / "Abort rebase" flow, which takes over from here.
          this.props.onDismissed()
          return
        case 'error':
          this.setState({
            busy: false,
            step: 'paused',
            pausedOutcome: 'error',
            error: 'The interactive rebase failed. See the log for details.',
          })
          return
      }
    } catch (e) {
      // Shown in the dialog, which stays open so the user can act on it.
      log.error('Arbor: interactive rebase failed', e)
      if (this.isMounted) {
        this.setState({ busy: false, error: describeError(e) })
      }
    }
  }

  private async continueRebase() {
    const { repository, dispatcher } = this.props

    if (this.state.busy) {
      return
    }

    this.setState({ busy: true, error: null })

    try {
      const outcome = await continueInteractiveRebase(repository)

      await dispatcher.refreshRepository(repository)

      if (!this.isMounted) {
        return
      }

      if (outcome === 'completed') {
        this.props.onDismissed()
        return
      }

      if (outcome === 'error') {
        this.setState({
          busy: false,
          pausedOutcome: 'error',
          error: 'The interactive rebase failed. See the log for details.',
        })
        return
      }

      this.setState({
        busy: false,
        pausedOutcome: outcome,
        pausedSha:
          outcome === 'stopped-for-edit'
            ? getFirstEditSha(this.state.plan)
            : null,
      })
    } catch (e) {
      // Shown in the dialog, which stays open so the user can act on it.
      log.error('Arbor: interactive rebase failed', e)
      if (this.isMounted) {
        this.setState({ busy: false, error: describeError(e) })
      }
    }
  }

  private async abortRebase() {
    const { repository, dispatcher } = this.props

    if (this.state.busy) {
      return
    }

    this.setState({ busy: true, error: null })

    try {
      await abortInteractiveRebase(repository)
      await dispatcher.refreshRepository(repository)

      if (this.isMounted) {
        this.props.onDismissed()
      }
    } catch (e) {
      // Shown in the dialog, which stays open so the user can act on it.
      log.error('Arbor: interactive rebase failed', e)
      if (this.isMounted) {
        this.setState({ busy: false, error: describeError(e) })
      }
    }
  }

  private renderError() {
    const error = this.state.error

    return error === null ? null : <DialogError>{error}</DialogError>
  }

  private renderStartEntry(commit: Commit) {
    return (
      <li
        key={commit.sha}
        className="arbor-rebase-start-entry"
        role="option"
        aria-selected={false}
        tabIndex={0}
        data-sha={commit.sha}
        onClick={this.onStartEntryClick}
        onKeyDown={this.onStartEntryKeyDown}
      >
        <span className="arbor-rebase-sha">{shortenSHA(commit.sha)}</span>
        <span className="arbor-rebase-summary">{commit.summary}</span>
      </li>
    )
  }

  private renderStartStep() {
    const { loading, commits } = this.state

    return (
      <DialogContent className="arbor-rebase-start">
        <p className="arbor-rebase-description">
          Choose the oldest commit to rewrite. Every commit from this one up to
          HEAD becomes part of the rebase.
        </p>
        {this.renderError()}
        {loading ? (
          <div className="arbor-rebase-loading">Loading commits…</div>
        ) : commits.length === 0 ? (
          <div className="arbor-rebase-empty">
            This repository doesn't have any commit to rewrite.
          </div>
        ) : (
          <ul
            className="arbor-rebase-start-list"
            role="listbox"
            aria-label="Commits, newest first"
          >
            {commits.map(commit => this.renderStartEntry(commit))}
          </ul>
        )}
      </DialogContent>
    )
  }

  private renderEntry(
    entry: IRebaseTodoEntry,
    index: number,
    grouping: IRebaseEntryGrouping,
    isFirst: boolean,
    isLast: boolean
  ) {
    const shortSha = shortenSHA(entry.sha)
    const option = getActionOption(entry.action)
    const descriptionId = `arbor-rebase-action-description-${entry.sha}`
    const className = classNames(
      'arbor-rebase-entry',
      `arbor-rebase-entry-${entry.action}`,
      {
        'is-dropped': entry.action === 'drop',
        'is-indented': grouping.indented,
        'is-dragging': this.state.draggingIndex === index,
        'is-drop-target': this.state.dragOverIndex === index,
      }
    )

    return (
      // The row itself isn't a widget, it only carries the drag and drop
      // handlers and listens for Alt+Up/Alt+Down. It is made focusable so that
      // the shortcuts apply to the row the user is on, which the a11y linter
      // can't express.
      // eslint-disable-next-line jsx-a11y/no-noninteractive-element-interactions
      <li
        key={entry.sha}
        ref={this.onEntryRef}
        className={className}
        data-sha={entry.sha}
        data-action={entry.action}
        // eslint-disable-next-line jsx-a11y/no-noninteractive-tabindex
        tabIndex={0}
        draggable={true}
        onDragStart={this.onDragStart}
        onDragOver={this.onDragOver}
        onDrop={this.onDrop}
        onDragEnd={this.onDragEnd}
        onKeyDown={this.onEntryKeyDown}
        aria-label={`${option.label} ${shortSha}: ${entry.summary}`}
      >
        <div className="arbor-rebase-entry-row">
          <span className="arbor-rebase-drag-handle" aria-hidden={true}>
            <Octicon symbol={octicons.grabber} />
          </span>
          <select
            className="arbor-rebase-action"
            aria-label={`Action for ${shortSha}`}
            aria-describedby={descriptionId}
            value={entry.action}
            disabled={this.state.busy}
            onChange={this.onActionChanged}
          >
            {RebaseActionOptions.map(actionOption => (
              <option key={actionOption.value} value={actionOption.value}>
                {actionOption.label}
              </option>
            ))}
          </select>
          <span className="arbor-rebase-sha">{shortSha}</span>
          <span className="arbor-rebase-entry-text">
            <span className="arbor-rebase-summary">{entry.summary}</span>
            <span
              className="arbor-rebase-action-description"
              id={descriptionId}
            >
              {option.description}
            </span>
          </span>
          <span className="arbor-rebase-entry-actions">
            <Button
              className="arbor-rebase-move-up"
              type="button"
              size="small"
              disabled={isFirst || this.state.busy}
              ariaLabel={`Move ${shortSha} up`}
              onClick={this.onMoveUpClick}
            >
              <Octicon symbol={octicons.arrowUp} />
            </Button>
            <Button
              className="arbor-rebase-move-down"
              type="button"
              size="small"
              disabled={isLast || this.state.busy}
              ariaLabel={`Move ${shortSha} down`}
              onClick={this.onMoveDownClick}
            >
              <Octicon symbol={octicons.arrowDown} />
            </Button>
          </span>
        </div>
        {entry.action === 'reword' && (
          <TextArea
            labelClassName="arbor-rebase-message"
            label={`New message for ${shortSha}`}
            value={entry.message ?? entry.summary}
            rows={3}
            disabled={this.state.busy}
            onChange={this.onMessageChanged}
          />
        )}
        {grouping.endsSquashGroup && (
          <TextArea
            labelClassName="arbor-rebase-message"
            label="Message of the combined commit (optional)"
            value={entry.message ?? ''}
            placeholder="Leave empty to keep the generated message"
            rows={3}
            disabled={this.state.busy}
            onChange={this.onMessageChanged}
          />
        )}
      </li>
    )
  }

  private renderPlanStep() {
    const { loading, plan, originalPlan, busy } = this.state

    if (loading) {
      return (
        <DialogContent className="arbor-rebase-plan-content">
          <div className="arbor-rebase-loading">Loading commits…</div>
        </DialogContent>
      )
    }

    const validationError = this.getValidationError()
    const unchanged = isRebasePlanUnchanged(originalPlan, plan)
    const grouping = getRebaseEntryGrouping(plan)

    return (
      <DialogContent className="arbor-rebase-plan-content">
        <div className="arbor-rebase-plan-toolbar">
          <p className="arbor-rebase-plan-subtitle">
            Commits are applied from top to bottom.
          </p>
          <span className="arbor-rebase-plan-actions">
            {this.props.fromCommitSha === undefined && (
              <Button
                className="arbor-rebase-change-start"
                type="button"
                size="small"
                disabled={busy}
                onClick={this.onChangeStartClick}
              >
                Change starting point
              </Button>
            )}
            <Button
              className="arbor-rebase-reset"
              type="button"
              size="small"
              disabled={busy || unchanged}
              onClick={this.onResetClick}
            >
              Reset
            </Button>
          </span>
        </div>
        {this.renderError()}
        {validationError !== null && (
          <DialogError>{validationError}</DialogError>
        )}
        <ul
          className="arbor-rebase-plan"
          aria-label="Rebase plan, oldest first"
        >
          {plan.map((entry, index) =>
            this.renderEntry(
              entry,
              index,
              grouping[index],
              index === 0,
              index === plan.length - 1
            )
          )}
        </ul>
        {unchanged && (
          <p className="arbor-rebase-unchanged-hint">
            Change at least one action to start the rebase.
          </p>
        )}
      </DialogContent>
    )
  }

  private renderPausedStep() {
    const { pausedOutcome, pausedSha, busy } = this.state

    return (
      <DialogContent className="arbor-rebase-paused">
        {this.renderError()}
        {pausedOutcome === 'stopped-for-edit' && (
          <p className="arbor-rebase-paused-message">
            Rebase paused to edit{' '}
            <span className="arbor-rebase-sha">
              {pausedSha === null ? 'a commit' : shortenSHA(pausedSha)}
            </span>
            . Amend your changes in the Changes tab, then continue.
          </p>
        )}
        {pausedOutcome === 'conflicts' && (
          <p className="arbor-rebase-paused-message">
            Resolve the conflicts (Changes tab), then continue.
          </p>
        )}
        {pausedOutcome === 'error' && (
          <p className="arbor-rebase-paused-message">
            The rebase didn't complete. Abort it to restore the previous state.
          </p>
        )}
        <span className="arbor-rebase-paused-actions">
          {pausedOutcome !== 'error' && (
            <Button
              className="arbor-rebase-continue"
              type="button"
              disabled={busy}
              onClick={this.onContinueClick}
            >
              Continue
            </Button>
          )}
          <Button
            className="arbor-rebase-abort"
            type="button"
            disabled={busy}
            onClick={this.onAbortClick}
          >
            Abort
          </Button>
        </span>
      </DialogContent>
    )
  }

  private renderFooter() {
    if (this.state.step === 'paused') {
      return null
    }

    return (
      <DialogFooter>
        <OkCancelButtonGroup
          okButtonText="Start rebase"
          okButtonDisabled={!this.canStartRebase()}
          okButtonTitle={this.getStartButtonTitle()}
          onOkButtonClick={this.onOkButtonClick}
          cancelButtonText="Cancel"
          cancelButtonDisabled={this.state.busy}
          onCancelButtonClick={this.onCancelButtonClick}
        />
      </DialogFooter>
    )
  }

  public render() {
    const { step } = this.state

    return (
      <Dialog
        id="arbor-interactive-rebase"
        title={__DARWIN__ ? 'Interactive Rebase' : 'Interactive rebase'}
        className="arbor-rebase-dialog"
        onDismissed={this.props.onDismissed}
        onSubmit={this.onFormSubmit}
        dismissDisabled={this.state.busy}
        backdropDismissable={false}
      >
        {step === 'start'
          ? this.renderStartStep()
          : step === 'plan'
          ? this.renderPlanStep()
          : this.renderPausedStep()}
        {this.renderFooter()}
      </Dialog>
    )
  }
}
