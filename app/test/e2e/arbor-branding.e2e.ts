/**
 * Arbor: E2E test of the app's branding (welcome flow, title bar, About).
 * Runs first (alphabetically), while the welcome flow is still showing.
 */

import * as fs from 'fs'
import * as path from 'path'
import { test, expect } from './e2e-fixtures'
import { clickAppMenuItem, openSmokeRepository } from './arbor-helpers'

test.describe.configure({ mode: 'serial' })

test.describe('Arbor branding', () => {
  test('welcomes the user to Arbor', async ({ mainWindow: page }) => {
    const welcome = page.locator('#start')
    // A previous test file sharing the app may have completed the flow.
    const shown = await welcome
      .waitFor({ state: 'visible', timeout: 15000 })
      .then(() => true)
      .catch(() => false)
    test.skip(!shown, 'The welcome flow was completed by a previous test file')
    await expect(welcome.locator('.welcome-title')).toHaveText(
      'Welcome to Arbor'
    )
    await expect(welcome).toContainText('GitLab')
    await page.screenshot({
      path: test.info().outputPath('arbor-welcome.png'),
    })
  })

  test('shows the Arbor logo in the title bar and the About dialog', async ({
    app,
    mainWindow: page,
  }) => {
    await openSmokeRepository(page)

    // The title bar shows the app icon once past the welcome flow (Windows
    // only: macOS uses its native title bar). It's the Arbor glyph, a tree
    // with four commit nodes, not GitHub's mark.
    if (process.platform === 'win32') {
      const icon = page.locator('#desktop-app-title-bar .app-icon')
      await expect(icon).toBeVisible({ timeout: 15000 })
      await expect(icon.locator('circle')).toHaveCount(4)
    }

    await clickAppMenuItem(app, 'about')
    const about = page.locator('dialog#about')
    await about.waitFor({ state: 'visible', timeout: 15000 })

    const logo = about.locator('.logo img')
    await expect(logo).toHaveAttribute('alt', 'Arbor')
    // The image shown is the Arbor logo generated by branding/make-logo.py.
    const src = decodeURIComponent((await logo.getAttribute('src')) ?? '')
    const file = src.replace(/^file:\/\/\/?/, '')
    const expected = path.join(
      __dirname,
      '..',
      '..',
      'static',
      'common',
      path.basename(file)
    )
    expect(fs.readFileSync(file).equals(fs.readFileSync(expected))).toBe(true)
    await about.screenshot({
      path: test.info().outputPath('arbor-about.png'),
    })
    await page.keyboard.press('Escape')
    await about.waitFor({ state: 'hidden', timeout: 15000 })
  })
})
